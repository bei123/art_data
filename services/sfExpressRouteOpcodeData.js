/**
 * 顺丰路由操作码官方对照表（路由查询 / 路由推送 opCode 参考）
 * @see https://open.sf-express.com/developSupport/734349?activeIndex=589678
 *
 * 字段说明：
 * - opCode: 路由操作码
 * - reasonCode: 原因码（空字符串表示无原因码）
 * - firstStatusCode / secondaryStatusCode: 「-」记为 null
 */

function r(opCode, reasonCode, name, firstStatusCode, firstStatusName, secondaryStatusCode, secondaryStatusName) {
  return {
    opCode: String(opCode),
    reasonCode: reasonCode != null && String(reasonCode).trim() !== '' ? String(reasonCode).trim() : '',
    name: String(name).trim(),
    firstStatusCode: firstStatusCode === '-' || firstStatusCode == null || firstStatusCode === '' ? null : Number(firstStatusCode),
    firstStatusName: String(firstStatusName).trim(),
    secondaryStatusCode: secondaryStatusCode === '-' || secondaryStatusCode == null || secondaryStatusCode === '' ? null : Number(secondaryStatusCode),
    secondaryStatusName: secondaryStatusName === '-' ? '' : String(secondaryStatusName).trim(),
  }
}

